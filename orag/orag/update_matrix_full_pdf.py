            "    t_embed_start = time.time()\n",
            "    # Simulation: 40ms per chunk on High, 100ms on Low\n",
            "    chunk_time = 0.10 if profile['profile'] == 'LOW' else 0.03\n",
            "    time.sleep(chunk_time * num_chunks)\n",
