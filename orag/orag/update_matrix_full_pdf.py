            "    t_model_loaded = time.time()\n",
            "    print(f\"  -> Loaded in {t_model_loaded - t0:.2f} s\")\n",
            "    \n",
            "    # 2. PDF Extraction & Chunking\n",
            "    print(\"[STEP 2] Extracting text from PDF and generating chunks...\")\n",
